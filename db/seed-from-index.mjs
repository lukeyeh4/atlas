// Generate db/seed.sql from the data constants in index.html, so the database
// starts from exactly what the app ships with. Every value is seeded with
// confidence 'sample' (the schema default).
//
//   node db/seed-from-index.mjs > db/seed.sql

import { readFileSync } from 'node:fs';

const html = readFileSync(new URL('../index.html', import.meta.url), 'utf8');

// Return the object/array literal assigned by `var NAME = ...`, skipping
// brackets inside strings and comments.
function literal(name) {
  const at = html.indexOf(`var ${name} = `);
  if (at < 0) throw new Error(`var ${name} not found in index.html`);
  let i = html.indexOf('=', at) + 1;
  while (/\s/.test(html[i])) i++;
  const open = html[i], close = open === '{' ? '}' : ']';
  let depth = 0, quote = null;
  for (let j = i; j < html.length; j++) {
    const ch = html[j];
    if (quote) {
      if (ch === '\\') j++;
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === "'" || ch === '"') quote = ch;
    else if (ch === '/' && html[j + 1] === '/') j = html.indexOf('\n', j);
    else if (ch === open) depth++;
    else if (ch === close && --depth === 0) {
      return Function(`"use strict"; return (${html.slice(i, j + 1)});`)();
    }
  }
  throw new Error(`unterminated literal for ${name}`);
}

const REGIONS = literal('REGIONS');
const SITES = literal('SITES');
const CITIES = literal('CITIES');
const FLOWS = literal('FLOWS');
const COUNTRY = literal('COUNTRY');

const q = (v) => (v == null ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const rows = (list) => list.map((r) => `  (${r.map(q).join(', ')})`).join(',\n');
const insert = (table, cols, list) =>
  list.length ? `insert into ${table} (${cols.join(', ')}) values\n${rows(list)};\n` : '';

const out = [
  '-- Generated by db/seed-from-index.mjs from index.html. Do not edit by hand.',
  '-- All values are the app\'s illustrative sample inputs (confidence = sample).',
  '',
  'begin;',
  '',
  insert('region', ['id', 'name'], Object.entries(REGIONS).map(([id, r]) => [id, r.n])),
  insert('region_input', ['region_id', 'key', 'value'],
    Object.entries(REGIONS).flatMap(([id, r]) =>
      ['ci', 'dec', 'wue', 'ws', 'fos'].filter((k) => r[k] != null).map((k) => [id, k, r[k]]))),
  insert('site', ['id', 'name', 'place', 'stage', 'lon', 'lat', 'region_id', 'note'], [
    ...SITES.map((s) => [s.id, s.n, s.p, s.s, s.c[0], s.c[1], s.r, s.note]),
    ...CITIES.map((c) => [c.id, c.n, c.p, null, c.c[0], c.c[1], c.r, null]),
  ]),
  insert('site_input', ['site_id', 'key', 'value'],
    SITES.flatMap((s) => ['p', 'u', 'pue', 'g', 'pop'].map((k) => [s.id, k, s.in[k]]))),
  insert('flow', ['from_site', 'to_site'], FLOWS),
  insert('country_value', ['country', 'key', 'value'],
    Object.entries(COUNTRY).flatMap(([name, v]) =>
      ['ci', 'ws', 'aq'].map((k, i) => [name, k, v[i]]).filter((r) => r[2] != null))),
  'commit;',
  '',
];

process.stdout.write(out.join('\n'));
